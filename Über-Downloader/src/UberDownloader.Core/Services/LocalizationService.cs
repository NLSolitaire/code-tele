    public string Format(string key, params object[] args)
    {
        try
        {
            return string.Format(Get(key), args);
        }
        catch
        {
            return Get(key);
        }
    }

    public string TranslateOption(string currentText)
    {
        if (string.IsNullOrWhiteSpace(currentText)) return currentText;

        foreach (var langDict in _translations.Values)
        {
            foreach (var kvp in langDict)
            {
                if (string.Equals(kvp.Value, currentText, StringComparison.OrdinalIgnoreCase))
                {
                    return Get(kvp.Key);
                }
            }
        }
        return currentText;
    }

    public string TranslateLogLine(string message)
    {
        if (string.IsNullOrWhiteSpace(message)) return message;

        // Static single-line logs
        if (message.StartsWith("Démarrage d'Über-Downloader", StringComparison.OrdinalIgnoreCase) ||
            message.StartsWith("Starting Über-Downloader", StringComparison.OrdinalIgnoreCase) ||
            message.StartsWith("Iniciando Über-Downloader", StringComparison.OrdinalIgnoreCase))
        {
            return Get("LogAppStarting");
        }

        if (message.StartsWith("Aucun journal disponible", StringComparison.OrdinalIgnoreCase) ||
            message.StartsWith("No logs available", StringComparison.OrdinalIgnoreCase) ||
            message.StartsWith("No hay registros disponibles", StringComparison.OrdinalIgnoreCase))
        {
            return Get("LogNoLogs");
        }

        if (message.StartsWith("Liste des téléchargements vidée", StringComparison.OrdinalIgnoreCase) ||
            message.StartsWith("Download list cleared", StringComparison.OrdinalIgnoreCase) ||
            message.StartsWith("Lista de descargas vaciada", StringComparison.OrdinalIgnoreCase))
        {
            return Get("LogDownloadListCleared");
        }

        // Regex patterns
        System.Text.RegularExpressions.Match m;

        // Card removed
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Carte retirée de la liste|Card removed from list|Tarjeta eliminada de la lista)\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogCardRemoved", m.Groups[1].Value.Trim());

        // Playlist removed
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Playlist retirée de la liste|Playlist removed from list|Lista de reproducción eliminada de la lista)\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogPlaylistRemoved", m.Groups[1].Value.Trim());

        // Paused
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Téléchargement mis en pause|Download paused|Descarga pausada)\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogDownloadPaused", m.Groups[1].Value.Trim());

        // Cancelled
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Téléchargement annulé|Download cancelled|Descarga cancelada)\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogDownloadCancelled", m.Groups[1].Value.Trim());

        // Live finalized
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Extrait de direct finalisé et sauvegardé|Live clip finalized and saved|Clip en directo finalizado y guardado)\s*:\s*(.*?)\s*->\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogLiveFinalized", m.Groups[1].Value.Trim(), m.Groups[2].Value.Trim());

        // Live deleted
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Extrait de direct supprimé|Live clip deleted|Clip en directo eliminado)\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogLiveDeleted", m.Groups[1].Value.Trim());

        // Auto resume item
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Reprise automatique au démarrage|Auto-resuming on startup|Reanudación automática al inicio)\s*:\s*'?([^']*)'?$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogAutoResumeItem", m.Groups[1].Value.Trim());

        // Auto resume playlist
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Reprise automatique au démarrage|Auto-resuming on startup|Reanudación automática al inicio)\s*:\s*(?:playlist|lista)\s*'([^']*)'\s*\(([^)]*)\)\.?$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success)
        {
            string countStr = System.Text.RegularExpressions.Regex.Match(m.Groups[2].Value, @"\d+").Value;
            return Format("LogAutoResumePlaylist", m.Groups[1].Value.Trim(), countStr);
        }

        // Download queued
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Téléchargement mis en file|Download queued|Descarga en cola)\s*:\s*(.*?)\s*\((https?://[^)]+)\)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogDownloadQueued", m.Groups[1].Value.Trim(), m.Groups[2].Value.Trim());

        // Download starting
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Démarrage du téléchargement yt-dlp|Starting yt-dlp download|Iniciando descarga yt-dlp)\s*:\s*(.*?)\s*\((https?://[^)]+)\)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogDownloadStarting", m.Groups[1].Value.Trim(), m.Groups[2].Value.Trim());

        // Download completed
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Téléchargement terminé avec succès|Download completed successfully|Descarga completada con éxito)\s*:\s*(.*?)\s*->\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogDownloadCompleted", m.Groups[1].Value.Trim(), m.Groups[2].Value.Trim());

        // Playlist report
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Rapport playlist|Playlist report|Informe de lista)\s*'([^']*)'\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogPlaylistReport", m.Groups[1].Value.Trim(), m.Groups[2].Value.Trim());

        // Sniff started
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:\[INFO\]\s*)?(?:Extraction manuelle lancée avec|Manual extraction started with|Extracción manual iniciada con)\s*'([^']*)'\s*(?:pour|for|para)\s*'([^']*)'\s*\((https?://[^)]+)\)\.\.\.$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogSniffStarted", m.Groups[1].Value.Trim(), m.Groups[2].Value.Trim(), m.Groups[3].Value.Trim());

        // Sniff success
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:\[(?:SUCCÈS|SUCCESS|ÉXITO)\]\s*)?(?:Flux vidéo extrait manuellement|Video stream manually extracted|Flujo de vídeo extraído manualmente)\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogSniffSuccess", m.Groups[1].Value.Trim());

        // Sniff failed
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Échec de l'extraction manuelle pour|Manual extraction failed for|Error en la extracción manual para)\s*'([^']*)'\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success) return Format("LogSniffFailed", m.Groups[1].Value.Trim(), m.Groups[2].Value.Trim());

        // Settings saved
        m = System.Text.RegularExpressions.Regex.Match(message, @"^(?:Paramètres sauvegardés|Settings saved|Ajustes guardados).*?(?:Langue|Language|Idioma)\s*:\s*([^,]+).*?(?:Vitesse|Speed|Velocidad)\s*:\s*([^,]+).*?(?:Raccourci|Shortcut|Atajo)\s*:\s*([^,]+).*?(?:Simultanés|Concurrent|Simultáneos)\s*:\s*([^,]+).*?(?:Essais auto|Auto-retries|Reintentos auto)\s*:\s*(.*)$", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
        if (m.Success)
        {
            return Format("LogSettingsSaved",
                TranslateOption(m.Groups[1].Value.Trim()),
                TranslateOption(m.Groups[2].Value.Trim()),
                m.Groups[3].Value.Trim(),
                TranslateOption(m.Groups[4].Value.Trim()),
                TranslateOption(m.Groups[5].Value.Trim()));
        }

        return message;
    }

    public void SetLanguage(string lang)
    {
        if (string.IsNullOrWhiteSpace(lang)) lang = "FR";
        lang = lang.Trim().ToUpperInvariant();
        if (lang != "FR" && lang != "EN" && lang != "ES") lang = "FR";

        CurrentLanguage = lang;
        LanguageChanged?.Invoke();
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
    }

    public string Get(string key)
    {
        if (_translations.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(key, out var val))
        {
            return val;
        }

        if (_translations["FR"].TryGetValue(key, out var fallback))
        {
            return fallback;
        }

        return key;
    }
